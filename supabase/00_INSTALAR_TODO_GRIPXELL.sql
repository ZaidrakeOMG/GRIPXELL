CREATE TABLE IF NOT EXISTS public.clientes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 nombre text NOT NULL CHECK(length(trim(nombre))>0),
 direccion text NOT NULL DEFAULT '', ciudad text NOT NULL DEFAULT '',
 codigo_postal text NOT NULL DEFAULT '', rfc text NOT NULL DEFAULT '',
 telefono text NOT NULL DEFAULT '', fecha_registro timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.ordenes (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 folio bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 17 INCREMENT BY 1) UNIQUE NOT NULL,
 cliente_id uuid NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
 fecha date NOT NULL DEFAULT current_date,
 tipo_venta text NOT NULL DEFAULT 'credito' CHECK(tipo_venta IN ('contado','credito')),
 subtotal numeric(14,2) NOT NULL DEFAULT 0 CHECK(subtotal>=0),
 iva numeric(14,2) NOT NULL DEFAULT 0 CHECK(iva>=0),
 total numeric(14,2) NOT NULL DEFAULT 0 CHECK(total>=0),
 enganche numeric(14,2) NOT NULL DEFAULT 0 CHECK(enganche>=0),
 abono_semanal numeric(14,2) NOT NULL DEFAULT 0 CHECK(abono_semanal>=0),
 estado text NOT NULL DEFAULT 'vigente' CHECK(estado IN ('vigente','pagada','cancelada')),
 observaciones text NOT NULL DEFAULT '',
 fecha_creacion timestamptz NOT NULL DEFAULT now(),
 fecha_actualizacion timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.orden_detalles (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 orden_id uuid NOT NULL REFERENCES public.ordenes(id) ON DELETE RESTRICT,
 cantidad numeric(14,3) NOT NULL DEFAULT 1 CHECK(cantidad>0),
 descripcion text NOT NULL CHECK(length(trim(descripcion))>0),
 precio_unitario numeric(14,2) NOT NULL DEFAULT 0 CHECK(precio_unitario>=0),
 importe numeric(14,2) GENERATED ALWAYS AS (round(cantidad*precio_unitario,2)) STORED
);
CREATE TABLE IF NOT EXISTS public.abonos (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 orden_id uuid NOT NULL REFERENCES public.ordenes(id) ON DELETE RESTRICT,
 fecha_pago date NOT NULL DEFAULT current_date,
 monto numeric(14,2) NOT NULL CHECK(monto>0),
 tipo_pago text NOT NULL DEFAULT 'abono' CHECK(tipo_pago IN ('abono','enganche','liquidacion')),
 metodo_pago text NOT NULL DEFAULT 'efectivo' CHECK(metodo_pago IN ('efectivo','transferencia','tarjeta','otro')),
 referencia text NOT NULL DEFAULT '',
 estado text NOT NULL DEFAULT 'vigente' CHECK(estado IN ('vigente','anulado')),
 motivo_anulacion text NOT NULL DEFAULT '',
 fecha_registro timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.documentos (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 orden_id uuid NOT NULL REFERENCES public.ordenes(id) ON DELETE RESTRICT,
 tipo_documento text NOT NULL CHECK(tipo_documento IN ('nota','estado_cuenta')),
 version integer NOT NULL DEFAULT 1 CHECK(version>0),
 archivo_storage text NOT NULL,
 total_guardado numeric(14,2) NOT NULL DEFAULT 0,
 abonado_guardado numeric(14,2) NOT NULL DEFAULT 0,
 saldo_guardado numeric(14,2) NOT NULL DEFAULT 0,
 fecha_generacion timestamptz NOT NULL DEFAULT now(),
 UNIQUE(orden_id,tipo_documento,version)
);
CREATE TABLE IF NOT EXISTS public.historial_movimientos (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 orden_id uuid NOT NULL REFERENCES public.ordenes(id) ON DELETE RESTRICT,
 tipo_movimiento text NOT NULL,
 descripcion text NOT NULL DEFAULT '',
 datos_anteriores jsonb, datos_nuevos jsonb,
 fecha_movimiento timestamptz NOT NULL DEFAULT now()
);
