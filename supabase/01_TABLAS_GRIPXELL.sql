CREATE OR REPLACE FUNCTION public.gripxell_auditar() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE v_orden uuid;
BEGIN
 IF TG_TABLE_NAME='ordenes' THEN v_orden:=COALESCE(NEW.id,OLD.id);
 ELSE v_orden:=COALESCE(NEW.orden_id,OLD.orden_id); END IF;
 INSERT INTO public.historial_movimientos(orden_id,tipo_movimiento,descripcion,datos_anteriores,datos_nuevos)
 VALUES(v_orden,TG_TABLE_NAME||'_'||lower(TG_OP), 'Movimiento automatico',
 CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) END,
 CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) END);
 RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS trg_auditar_ordenes ON public.ordenes;
CREATE TRIGGER trg_auditar_ordenes AFTER INSERT OR UPDATE ON public.ordenes
FOR EACH ROW EXECUTE FUNCTION public.gripxell_auditar();
DROP TRIGGER IF EXISTS trg_auditar_detalles ON public.orden_detalles;
CREATE TRIGGER trg_auditar_detalles AFTER INSERT OR UPDATE OR DELETE ON public.orden_detalles
FOR EACH ROW EXECUTE FUNCTION public.gripxell_auditar();
DROP TRIGGER IF EXISTS trg_auditar_abonos ON public.abonos;
CREATE TRIGGER trg_auditar_abonos AFTER INSERT OR UPDATE OR DELETE ON public.abonos
FOR EACH ROW EXECUTE FUNCTION public.gripxell_auditar();

CREATE OR REPLACE FUNCTION public.gripxell_no_borrar_orden() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
 RAISE EXCEPTION 'No se permite borrar ordenes; usa estado cancelada';
END $$;
DROP TRIGGER IF EXISTS trg_no_borrar_orden ON public.ordenes;
CREATE TRIGGER trg_no_borrar_orden BEFORE DELETE ON public.ordenes
FOR EACH ROW EXECUTE FUNCTION public.gripxell_no_borrar_orden();

